#!/usr/bin/env python3
"""Embeds the web app's built-in themes (magpie/static/themes/*.json) in ios/Magpie/BuiltInThemes.swift,
so the iOS app has them offline. Run after adding or changing a theme:

  python ios/tools/gen_themes.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THEMES = sorted((ROOT / "magpie" / "static" / "themes").glob("*.json"))
OUT = ROOT / "ios" / "Magpie" / "BuiltInThemes.swift"

entries = []
for path in THEMES:
    theme = json.loads(path.read_text(encoding="utf-8"))
    entries.append(json.dumps(theme, separators=(",", ":"), sort_keys=True))

body = ",\n".join(f'        ##"{e}"##' for e in entries)   # ##: the colours contain "# which would end a #"..."# string
OUT.write_text(f'''// Generated by ios/tools/gen_themes.py from magpie/static/themes/*.json. Do not edit by hand.
import Foundation

enum BuiltInThemes {{
    static let json: [String] = [
{body},
    ]
}}
''', encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({len(entries)} themes)")
